-- Replace the U2 minimum-posting check with the U6 command-specific invariant.
-- Every terminal financial command has one generation-matched transaction and
-- the exact shape needed for its simulated operation.
CREATE OR REPLACE FUNCTION ritual_private.validate_simulation_command_ledger()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE transaction_count integer;
DECLARE cash_count integer;
DECLARE position_count integer;
DECLARE order_count integer;
DECLARE transaction_generation integer;
DECLARE transaction_portfolio uuid;
BEGIN
  SELECT count(*) INTO transaction_count
  FROM public.ledger_transactions
  WHERE tenant_id=NEW.tenant_id AND command_id=NEW.id;
  SELECT reset_generation,portfolio_id
    INTO transaction_generation,transaction_portfolio
  FROM public.ledger_transactions
  WHERE tenant_id=NEW.tenant_id AND command_id=NEW.id
  LIMIT 1;
  SELECT count(*) INTO cash_count
  FROM public.cash_ledger_entries AS entry
  JOIN public.ledger_transactions AS transaction
    ON transaction.tenant_id=entry.tenant_id AND transaction.id=entry.transaction_id
  WHERE transaction.tenant_id=NEW.tenant_id AND transaction.command_id=NEW.id;
  SELECT count(*) INTO position_count
  FROM public.position_ledger_entries AS entry
  JOIN public.ledger_transactions AS transaction
    ON transaction.tenant_id=entry.tenant_id AND transaction.id=entry.transaction_id
  WHERE transaction.tenant_id=NEW.tenant_id AND transaction.command_id=NEW.id;
  SELECT count(*) INTO order_count
  FROM public.simulated_orders
  WHERE tenant_id=NEW.tenant_id AND command_id=NEW.id;

  IF NEW.status='rejected' AND transaction_count <> 0 THEN
    RAISE EXCEPTION 'rejected command cannot have a ledger effect'
      USING ERRCODE = '23514';
  END IF;
  IF NEW.status <> 'committed' THEN RETURN NULL; END IF;
  IF transaction_count <> 1 OR transaction_generation <> NEW.reset_generation
     OR transaction_portfolio <> NEW.portfolio_id THEN
    RAISE EXCEPTION 'committed command requires one matching-generation transaction'
      USING ERRCODE = '23514';
  END IF;
  IF NEW.command_type='contribution'
     AND (cash_count <> 1 OR position_count <> 0 OR order_count <> 0) THEN
    RAISE EXCEPTION 'contribution posting shape is incomplete' USING ERRCODE='23514';
  ELSIF NEW.command_type='order'
     AND (cash_count <> 1 OR position_count <> 1 OR order_count <> 1) THEN
    RAISE EXCEPTION 'order posting shape is incomplete' USING ERRCODE='23514';
  ELSIF NEW.command_type='rebalance'
     AND (position_count < 1 OR cash_count <> position_count OR order_count <> 0) THEN
    RAISE EXCEPTION 'rebalance posting shape is incomplete' USING ERRCODE='23514';
  ELSIF NEW.command_type='recurring'
     AND (position_count < 1 OR cash_count <> position_count + 1 OR order_count <> 0) THEN
    RAISE EXCEPTION 'recurring allocation posting shape is incomplete' USING ERRCODE='23514';
  END IF;
  RETURN NULL;
END
$$;
