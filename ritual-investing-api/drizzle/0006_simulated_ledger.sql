-- Preview economics are frozen at creation. Only the lifecycle pointer may
-- advance, and a terminal preview cannot be reopened or rewritten.
CREATE OR REPLACE FUNCTION ritual_private.validate_order_preview_transition()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF OLD.status <> 'active' THEN
    RAISE EXCEPTION 'order preview is immutable after terminal state'
      USING ERRCODE = '55000';
  END IF;
  IF NEW.id IS DISTINCT FROM OLD.id
     OR NEW.tenant_id IS DISTINCT FROM OLD.tenant_id
     OR NEW.reset_generation IS DISTINCT FROM OLD.reset_generation
     OR NEW.portfolio_id IS DISTINCT FROM OLD.portfolio_id
     OR NEW.asset_id IS DISTINCT FROM OLD.asset_id
     OR NEW.side IS DISTINCT FROM OLD.side
     OR NEW.requested_notional_minor IS DISTINCT FROM OLD.requested_notional_minor
     OR NEW.requested_quantity IS DISTINCT FROM OLD.requested_quantity
     OR NEW.frozen_price_minor IS DISTINCT FROM OLD.frozen_price_minor
     OR NEW.quote_snapshot_id IS DISTINCT FROM OLD.quote_snapshot_id
     OR NEW.input_version IS DISTINCT FROM OLD.input_version
     OR NEW.observed_at IS DISTINCT FROM OLD.observed_at
     OR NEW.expires_at IS DISTINCT FROM OLD.expires_at THEN
    RAISE EXCEPTION 'order preview economics are immutable'
      USING ERRCODE = '55000';
  END IF;
  IF NEW.status NOT IN ('active','executed','expired','invalidated')
     OR (NEW.status IN ('executed','invalidated') AND NEW.executed_command_id IS NULL) THEN
    RAISE EXCEPTION 'invalid order preview transition'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$$;
ALTER FUNCTION ritual_private.validate_order_preview_transition()
  OWNER TO ritual_function_owner;
REVOKE ALL ON FUNCTION ritual_private.validate_order_preview_transition()
  FROM PUBLIC;
CREATE TRIGGER order_previews_frozen
  BEFORE UPDATE ON order_previews
