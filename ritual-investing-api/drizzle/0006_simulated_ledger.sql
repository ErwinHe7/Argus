    ON portfolio.tenant_id=account.tenant_id
      AND portfolio.reset_generation=state.reset_generation
      AND portfolio.is_default
      AND portfolio.status='active'
  WHERE account.auth0_subject=verified_subject
  LIMIT 1;
END
