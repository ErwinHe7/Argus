  FROM ritual_private.bootstrap_member_account_u3(verified_subject);

  RETURN QUERY
  SELECT
    account.id,
    account.status,
    profile.display_name,
    profile.locale,
    preference.theme_mode,
    preference.ritual_mode,
    preference.timezone,
    preference.version,
    onboarding.current_step,
    onboarding.completed_steps,
    onboarding.version,
    plan.code,
    entitlement.status,
    portfolio.id,
    portfolio.name,
    portfolio.currency,
    portfolio.status,
    portfolio.version,
    now()
  FROM public.accounts AS account
  JOIN public.profiles AS profile ON profile.tenant_id=account.tenant_id
  JOIN public.preferences AS preference ON preference.tenant_id=account.tenant_id
  JOIN public.onboarding_states AS onboarding ON onboarding.tenant_id=account.tenant_id
  JOIN public.tenant_demo_states AS state ON state.tenant_id=account.tenant_id
  JOIN public.tenant_entitlements AS entitlement
