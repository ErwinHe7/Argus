CREATE OR REPLACE FUNCTION ritual_private.validate_intention_current_projection()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE run_watermark bigint;
DECLARE run_generation integer;
DECLARE run_reset_generation integer;
BEGIN
  IF TG_OP='UPDATE' AND (
    NEW.current_projection_watermark < OLD.current_projection_watermark
    OR (
      NEW.current_projection_watermark = OLD.current_projection_watermark
      AND NEW.current_projection_generation < OLD.current_projection_generation
    )
  ) THEN
    RAISE EXCEPTION 'intention current projection cannot regress'
      USING ERRCODE = '23514';
  END IF;
  IF NEW.current_projection_run_id IS NULL THEN
    IF NEW.current_projection_watermark <> 0
       OR NEW.current_projection_generation <> 0
       OR (TG_OP='UPDATE' AND OLD.current_projection_run_id IS NOT NULL) THEN
      RAISE EXCEPTION 'intention current projection cannot regress'
        USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
  END IF;
  SELECT ledger_watermark,projection_generation,reset_generation
  INTO run_watermark,run_generation,run_reset_generation
  FROM public.projection_runs
  WHERE tenant_id=NEW.tenant_id AND intention_id=NEW.id
    AND id=NEW.current_projection_run_id;
  IF run_watermark IS NULL
     OR run_watermark <> NEW.current_projection_watermark
     OR run_generation <> NEW.current_projection_generation
     OR run_reset_generation <> NEW.reset_generation THEN
    RAISE EXCEPTION 'intention pointer must match its current projection run'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$$;
